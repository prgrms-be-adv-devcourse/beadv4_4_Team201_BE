    CONSTRAINT product_stock_history_change_type_check CHECK (((change_type)::text = ANY ((ARRAY['MANUAL_ADJUST'::character varying, 'ORDER_DEDUCT'::character varying, 'ORDER_RESTORE'::character varying])::text[])))
);

ALTER TABLE product_stock_history ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
