-- bc/catalog: Products, Wishlists, Carts

CREATE TABLE product (
    price integer NOT NULL,
    stock integer NOT NULL,
    created_at timestamp(6) NOT NULL,
    id bigint NOT NULL,
    seller_id bigint NOT NULL,
    updated_at timestamp(6) NOT NULL,
    created_by character varying(255),
    description character varying(255) NOT NULL,
    name character varying(255) NOT NULL,
    status character varying(255) NOT NULL,
    updated_by character varying(255),
    image_key character varying(500),
    category character varying(50),
    CONSTRAINT product_status_check CHECK (((status)::text = ANY ((ARRAY['DRAFT'::character varying, 'REJECTED'::character varying, 'ACTIVE'::character varying, 'INACTIVE'::character varying])::text[]))),
    CONSTRAINT product_category_check CHECK (((category)::text = ANY ((ARRAY['ELECTRONICS'::character varying, 'BEAUTY'::character varying, 'FASHION'::character varying, 'LIVING'::character varying, 'FOODS'::character varying, 'TOYS'::character varying, 'OUTDOOR'::character varying, 'PET'::character varying, 'KITCHEN'::character varying])::text[])))
);

ALTER TABLE product ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME product_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

